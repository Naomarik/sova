// Transport (§app/transport): reading a transport, and the acts that only your click on this device's page
// takes. A script, a chat, an extension's key or another computer running an act is refused with where to
// click (§app.transport/start), so no command starts, steers or brings back a transport.
import type { CommandEntry, CommandParam } from "./types.ts";

const session: CommandParam = { type: "session", description: "The chat, by its path", in: "query", key: "path", required: true };
const tid: CommandParam = { type: "string", description: "The transport's id (tr_…)", in: "path", key: "tid", required: true };
const act = (id: string, label: string, summary: string, verb: string): CommandEntry => ({
  id,
  label,
  summary,
  effect: "changes",
  params: { transport: tid },
  route: { method: "POST", path: `/api/transport/:tid/${verb}` },
  sessionKey: null,
  sessionFile: "never",
  meshNeed: "full",
});

