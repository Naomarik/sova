import assert from "node:assert/strict";
import { join } from "node:path";
import { describe, test } from "node:test";
import { writeFileSync } from "node:fs";
import { APP, settled, setup } from "./testing/scenario-kit";
import { Fixture, git, until } from "./testing/repo";
import { queueReadingAt } from "../nothing-left";
import { draftProofVia, draftsLeft } from "../spec-drafts-state";
import { execGit } from "../worktrees";

/**
 * §chat.worktrees/nothing-left through the real queue on the real run: the Ready list, the Land gate and the run's stop
 * read one answer, a landing of nothing never moves the target, and real work past a landing stays landable.
 */

const SENTENCE = (target: string) => `Nothing to land: everything on this branch is already on ${target}.`;

/** The real history: a commit, the target moves, the branch merges the target, and the pin lands (the catch-up merge
 *  stays behind on the branch). `conflicting`: the merge holds a hand edit the target then rewrites, so the trial conflicts. */
async function landedWithLeftover(fx: Fixture, h: Awaited<ReturnType<typeof setup>>["h"], o: { conflicting?: boolean; withoutSpecs?: boolean; draft?: boolean } = {}) {
  const b = fx.branch("left", { "left.txt": "left\n", "gen.txt": "from the branch\n" });
  fx.moveTargetOutside({ "first.txt": "first\n" });
  git(b.checkout, ["merge", "-q", "--no-ff", "--no-edit", fx.target]);
  if (o.draft) fx.draft(b.checkout, "doc");
  const merge = git(b.checkout, ["rev-parse", "HEAD"]);
  const e = await h.add({ branch: b.branch, commit: b.commit, ...(o.withoutSpecs ? { withoutSpecs: true } : {}) });
  const landed = await h.waitEntry(e.id, settled);
  assert.equal(landed.state, "landed", `${landed.state}: ${landed.reason}`);
  if (o.conflicting) {
    git(b.checkout, ["commit", "-q", "--amend", "--no-edit", "--allow-empty"]);
    fx.moveTargetOutside({ "gen.txt": "regenerated on the target\n" });
    writeFileSync(join(b.checkout, "gen.txt"), "regenerated by hand on the branch\n");
    git(b.checkout, ["add", "gen.txt"]);
    git(b.checkout, ["commit", "-q", "--amend", "--no-edit"]);
  }
  return { b, merge: git(b.checkout, ["rev-parse", "HEAD"]), wasMerge: merge, landed };
}

describe("nothing left to land", () => {
  test("a catch-up merge left behind: off the Ready list, Land refused with the sentence; nothing recorded, nothing runs, the target stays", async () => {
    const { fx, h } = await setup();
    const { b, landed } = await landedWithLeftover(fx, h);
    assert.equal(landed.newerCommits, undefined, "a catch-up merge is no newer commit");
    const v = await h.view();
    assert.ok(!(v.ready ?? []).some((r) => r.branch === b.branch), "no Ready row");
    assert.equal(v.recent.find((r) => r.entry.id === landed.id)?.entry.newerCommits, undefined, "and none on its row");
    const before = fx.head();
    const pushed = fx.originHead();
    const entries = (await h.view()).recent.length;
    const mark = fx.calls().length;
    const r = await h.tryAdd({ branch: b.branch });
    assert.deepEqual(r, { ok: false, code: "invalid-request", message: SENTENCE(fx.target) });
    assert.equal(fx.head(), before, "the target didn't move");
    assert.equal(fx.originHead(), pushed, "nothing pushed");
    assert.equal(fx.callsSince(mark).length, 0, "no check ran");
    assert.equal((await h.view()).recent.length, entries, "no entry");
  });

  test("the same once the leftover conflicts with the target (the trial can't speak for it)", async () => {
    const { fx, h } = await setup();
    const { b, merge } = await landedWithLeftover(fx, h, { conflicting: true });
    assert.throws(() => git(fx.project, ["merge-tree", "--write-tree", "--no-messages", fx.target, merge]), "it does conflict");
    const v = await h.view();
    assert.ok(!(v.ready ?? []).some((r) => r.branch === b.branch));
    const r = await h.tryAdd({ branch: b.branch });
    assert.deepEqual(r, { ok: false, code: "invalid-request", message: SENTENCE(fx.target) });
  });

  test("a real commit after the landing is work: on the Ready list, counted, and Land lands exactly it", async () => {
    const { fx, h } = await setup();
    const { b, landed } = await landedWithLeftover(fx, h);
    const real = fx.commitIn(b.checkout, { "real.txt": "real\n" }, "real work");
    const v = await until("the row of real work", async () => {
      const next = await h.queue().view();
      return (next.ready ?? []).some((x) => x.branch === b.branch) ? next : null;
    });
    assert.equal((v.ready ?? []).find((x) => x.branch === b.branch)?.commit, real);
    assert.equal(v.recent.find((r) => r.entry.id === landed.id)?.entry.newerCommits, 1, "one real commit, the merge not counted");
    const e = await h.add({ branch: b.branch });
    const done = await h.waitEntry(e.id, settled);
    assert.equal(done.state, "landed", `${done.state}: ${done.reason}`);
    assert.equal(fx.fileAt(fx.head(), "real.txt"), "real\n");
  });

  test("a commit past the approved one that is only a merge counts for nothing while it waits; a real one counts", async () => {
    const { fx, h } = await setup();
    const hold = fx.branch("hold", { "tests/h.txt": "gate hold\n" });
    const eh = await h.add({ branch: hold.branch });
    await until("hold at its gate", () => fx.atGate("hold"));
    const b = fx.branch("b", { "b.txt": "one\n" });
    const eb = await h.add({ branch: b.branch });
    git(b.checkout, ["merge", "-q", "--no-ff", "--no-edit", fx.target, "-s", "ours"], { allowFail: true });
    const v = await h.queue().view();
    assert.equal(v.waiting.find((x) => x.id === eb.id)?.newerCommits, undefined);
    fx.commitIn(b.checkout, { "later.txt": "x\n" }, "real");
    const v2 = await h.queue().view();
    assert.equal(v2.waiting.find((x) => x.id === eb.id)?.newerCommits, 1);
    fx.openGate("hold");
    await h.waitEntry(eh.id, settled);
    await h.waitEntry(eb.id, settled);
  });

  test("every entry speaks, not the view's window: the reading a row and Land rest on names each landing", async () => {
    const { fx, h } = await setup();
    const { b, landed } = await landedWithLeftover(fx, h);
    const reading = queueReadingAt(fx.project);
    assert.ok(reading);
    assert.deepEqual(reading!.landings(b.branch).pins, [landed.commit]);
    assert.equal(reading!.approvedAt(b.branch, landed.commit), true, "landed at the approved commit");
  });

  test("the target took the same content while it waited: the run stops, cancelled with the sentence; no check, no review, the target stays", async () => {
    const { fx, h } = await setup();
    const hold = fx.branch("hold", { "tests/h.txt": "gate hold\n", "same.txt": "same\n" });
    const eh = await h.add({ branch: hold.branch });
    await until("hold at its gate", () => fx.atGate("hold"));
    const b = fx.branch("b", { "same.txt": "same\n" });
    const eb = await h.add({ branch: b.branch });
    fx.openGate("hold");
    assert.equal((await h.waitEntry(eh.id, settled)).state, "landed");
    const before = fx.head();
    const mark = fx.calls().length;
    const done = await h.waitEntry(eb.id, settled);
    assert.equal(done.state, "cancelled");
    assert.equal(done.reason, SENTENCE(fx.target));
    assert.equal(fx.head(), before);
    assert.equal(fx.callsSince(mark).length, 0, "no check ran");
    const run = h.run(done.runs.at(-1)!);
    assert.deepEqual([run.verdict, run.blame], ["cancelled", undefined], "nothing blamed");
    assert.ok(!run.steps.some((s) => s.kind === "docs" || s.id === "review"), "stopped before the rest");
  });
});

describe("only spec drafts left", () => {
  const specFirst = async () => {
    const s = await setup();
    await s.fx.withSpec();
    return s;
  };

  test("landed without its specs, a catch-up merge on top: its row says so; Land lands just the drafts, one spec commit; without its specs is refused", async () => {
    const { fx, h } = await specFirst();
    const { b } = await landedWithLeftover(fx, h, { withoutSpecs: true, draft: true });
    const v = await h.view();
    const row = (v.ready ?? []).find((r) => r.branch === b.branch);
    assert.equal(row?.draftsOnly, 1, "one spec draft left");
    assert.deepEqual(row?.left, { whole: "work", code: "nothing" });
    assert.deepEqual(await h.tryAdd({ branch: b.branch, withoutSpecs: true }), { ok: false, code: "invalid-request", message: SENTENCE(fx.target) });
    const before = fx.head();
    const e = await h.add({ branch: b.branch });
    const done = await h.waitEntry(e.id, settled);
    assert.equal(done.state, "landed", `${done.state}: ${done.reason}`);
    assert.match(fx.fileAt(fx.head(), ".sova/spec/claims/b/doc.md") ?? "", /does its one thing/);
    const changed = git(fx.project, ["diff", "--name-only", before, fx.head()]).split("\n");
    assert.ok(changed.every((f) => f.startsWith(".sova/spec/")), `only the docs: ${changed.join(", ")}`);
    assert.equal(git(fx.project, ["rev-list", "--count", `${before}..${fx.head()}`]), "1", "one docs commit: no merge of the leftover");
    assert.ok(!((await h.view()).ready ?? []).some((r) => r.branch === b.branch), "and then nothing is left");
  });

  test("guard: a leftover merge that conflicts isn't skipped on the label's word: it goes to the conflict step and the target stays", async () => {
    const { fx, h } = await specFirst();
    const { b } = await landedWithLeftover(fx, h, { withoutSpecs: true, draft: true, conflicting: true });
    const row = ((await h.view()).ready ?? []).find((r) => r.branch === b.branch);
    assert.equal(row?.draftsOnly, 1, "the label says only drafts are left");
    const before = fx.head();
    const e = await h.add({ branch: b.branch });
    const done = await h.waitEntry(e.id, (x) => x.state === "conflict");
    assert.equal(done.state, "conflict");
    assert.equal(fx.head(), before, "never read Landed");
  });

  test("guard: a merge carrying real edits past a landing, approved for its drafts: the run merges it and the edit lands", async () => {
    const { fx, h } = await specFirst();
    const { b } = await landedWithLeftover(fx, h, { withoutSpecs: true, draft: true });
    // A hand edit inside the merge commit: the answer looks at which commits exist, so the label still says the code landed.
    writeFileSync(join(b.checkout, "hand.txt"), "edited inside the merge\n");
    git(b.checkout, ["add", "hand.txt"]);
    git(b.checkout, ["commit", "-q", "--amend", "--no-edit"]);
    const row = ((await h.view()).ready ?? []).find((r) => r.branch === b.branch);
    assert.equal(row?.draftsOnly, 1, "the label reads code landed");
    const e = await h.add({ branch: b.branch });
    const done = await h.waitEntry(e.id, settled);
    assert.equal(done.state, "landed", `${done.state}: ${done.reason}`);
    assert.equal(fx.fileAt(fx.head(), "hand.txt"), "edited inside the merge\n", "the edit reached the target");
  });

  test("a branch on the target with an unproved draft: not refused, and its draft lands", async () => {
    const { fx, h } = await specFirst();
    const b = fx.branch("on", { "src/app.txt": APP("line 3 changed") });
    fx.draft(b.checkout, "doc");
    const e = await h.add({ branch: b.branch, withoutSpecs: true });
    assert.equal((await h.waitEntry(e.id, settled)).state, "landed");
    git(fx.project, ["merge-base", "--is-ancestor", b.commit, fx.head()]);
    const row = ((await h.queue().view()).ready ?? []).find((r) => r.branch === b.branch);
    assert.equal(row?.draftsOnly, 1);
    assert.equal(row?.ahead, 0);
    const again = await h.add({ branch: b.branch });
    assert.equal((await h.waitEntry(again.id, settled)).state, "landed");
    assert.match(fx.fileAt(fx.head(), ".sova/spec/claims/b/doc.md") ?? "", /does its one thing/);
  });
});

describe("a draft proved landed", () => {
  const ancestor = async (c: string, ref: string, cwd: string) => (await execGit(["merge-base", "--is-ancestor", c, ref], { cwd })).code === 0;
  const proofRepo = async () => {
    const { fx, h } = await setup();
    await fx.withSpec();
    const b = fx.branch("old", { "src/app.txt": APP("line 3 changed") });
    fx.draft(b.checkout, "old");
    return { fx, h, b };
  };

  test("matching the target at the commit that landed it, the spec having moved on since and no receipt: proved; edited since: not", async () => {
    const { fx, h, b } = await proofRepo();
    const e = await h.add({ branch: b.branch });
    assert.equal((await h.waitEntry(e.id, settled)).state, "landed");
    // Older landings carried no receipt.
    const file = join(b.checkout, ".sova/spec/drafts/old/draft.json");
    const d = JSON.parse((await import("node:fs")).readFileSync(file, "utf8")) as Record<string, unknown>;
    delete d.landed;
    delete d.promotions;
    writeFileSync(file, JSON.stringify(d, null, 2));
    // The target's spec moves on over the same promise.
    fx.commitIn(fx.project, { ".sova/spec/claims/b/old.md": "# §b/old\n\nThe promise now says something else.\n" }, "spec moves on");
    assert.deepEqual(await draftsLeft(b.checkout, ancestor), ["old"], "what today's rule reads");
    const proof = draftProofVia(execGit);
    assert.deepEqual(await draftsLeft(b.checkout, ancestor, proof), [], "proved at the commit whose subject landed it");
    fx.editDraft(b.checkout, "old", "The old feature now does something new.");
    assert.deepEqual(await draftsLeft(b.checkout, ancestor, proof), ["old"], "a draft edited since is proved by none");
  });

  test("matching the target now, with no landing named: proved", async () => {
    const { fx, b } = await proofRepo();
    const body = (await import("node:fs")).readFileSync(join(b.checkout, ".sova/spec/drafts/old/spec/claims/b/old.md"), "utf8");
    const rec = (await import("node:fs")).readFileSync(join(b.checkout, ".sova/spec/drafts/old/spec/claims/b/old.json"), "utf8");
    fx.commitIn(fx.project, { ".sova/spec/claims/b/old.md": body, ".sova/spec/claims/b/old.json": rec }, "hand landed, no subject");
    assert.deepEqual(await draftsLeft(b.checkout, ancestor, draftProofVia(execGit)), []);
  });

  test("never landed: not proved, and it counts", async () => {
    const { b } = await proofRepo();
    assert.deepEqual(await draftsLeft(b.checkout, ancestor, draftProofVia(execGit)), ["old"]);
  });
});
