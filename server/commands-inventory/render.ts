// docs/commands.md, rendered from the inventory baseline and the catalogue. Pure: the test compares
// it to the committed file, and scripts/commands-inventory.mjs writes it (`--check` refuses drift).
// Erasable syntax only and `.ts` import extensions: the script loads it through Node's type stripping.
import { COMMANDS } from "../../shared/commands-catalog.ts";
import { ROUTE_CLASSES, type Inventory, type RouteRow } from "./scan.ts";

const code = (s: string) => `\`${s.replace(/`/g, "\\`")}\``;
const cell = (s: string) => s.replace(/\|/g, "\\|");

/** Rows sorted by path, then method, so a route's verbs sit together. */
function byPath(rows: [string, RouteRow][]): [string, RouteRow][] {
  const split = (k: string) => [k.slice(k.indexOf(" ") + 1), k.slice(0, k.indexOf(" "))] as const;
  return [...rows].sort((a, b) => {
    const [pa, ma] = split(a[0]);
    const [pb, mb] = split(b[0]);
    return pa < pb ? -1 : pa > pb ? 1 : ma < mb ? -1 : ma > mb ? 1 : 0;
  });
}

export function renderCommandsDoc(inv: Inventory): string {
  const rows = Object.entries(inv.routes);
  const of = (is: string) => byPath(rows.filter(([, r]) => r.is === is));
  const commandRoutes = of("command");
  const pending = of("pending");
  const toolCount = Object.values(inv.tools).reduce((n, t) => n + t.length, 0);
  const keyCount = Object.values(inv.keydown).reduce((n, t) => n + t.length, 0);
  const L: string[] = [];
  L.push("# Commands inventory");
  L.push("");
  L.push("<!-- Generated by `node scripts/commands-inventory.mjs` from server/commands-inventory/baseline.json and shared/commands-catalog.ts. Do not edit by hand. -->");
  L.push("");
  L.push("Every route Sova's main listener registers is exactly one of three things: a catalogue entry");
  L.push("(`shared/commands-catalog.ts`), a declared class that is not a command, or a row on the pending");
  L.push("baseline, which only shrinks. Each route's mesh need is what `server/mesh/access.ts`");
  L.push("`classifyRequest` gives it, pinned so that no change widens what a peer can reach without showing");
  L.push("up here. `server/commands-inventory.test.ts` holds all of it, exact both ways. The guide is");
  L.push("`agents/server/commands/overview.md`.");
  L.push("");
  L.push("## Counts");
  L.push("");
  L.push("| What | Count |");
  L.push("| --- | ---: |");
  L.push(`| Routes registered | ${rows.length} |`);
  L.push(`| Routes a catalogue entry points at | ${commandRoutes.length} |`);
  L.push(`| Catalogue entries | ${COMMANDS.length} |`);
  for (const c of ROUTE_CLASSES) L.push(`| Class: ${c.label} | ${of(c.id).length} |`);
  L.push(`| Pending (not yet a command) | ${pending.length} |`);
  L.push(`| Chat socket frame types | ${inv.frames.length} |`);
  L.push(`| Document/window keydown listeners | ${keyCount} |`);
  L.push(`| Hand-written tool specs | ${toolCount} |`);
  L.push("");
  L.push("## Catalogue entries");
  L.push("");
  L.push("| Id | Label | Effect | Route | Mesh need |");
  L.push("| --- | --- | --- | --- | --- |");
  for (const c of COMMANDS) L.push(`| ${code(c.id)} | ${cell(c.label)} | ${c.effect} | ${code(`${c.route.method} ${c.route.path}`)} | ${c.meshNeed} |`);
  L.push("");
  L.push("## Pending routes");
  L.push("");
  L.push("Not yet a command and in no class. The list only shrinks: a route that gains an entry, or joins a");
  L.push("class, leaves it, and a new route never joins it.");
  L.push("");
  L.push("| Route | Mesh need |");
  L.push("| --- | --- |");
  for (const [k, r] of pending) L.push(`| ${code(k)} | ${r.need} |`);
  L.push("");
  L.push("## Not-a-command classes");
  for (const c of ROUTE_CLASSES) {
    const mine = of(c.id);
    L.push("");
    L.push(`### ${c.label} (${mine.length})`);
    L.push("");
    L.push(c.why);
    if (mine.length) {
      L.push("");
      L.push("| Route | Mesh need |");
      L.push("| --- | --- |");
      for (const [k, r] of mine) L.push(`| ${code(k)} | ${r.need} |`);
    } else {
      L.push("");
      L.push("No route of the main listener's test build is in this class.");
    }
  }
  L.push("");
  L.push("## Routes catalogue entries point at");
  L.push("");
  L.push("| Route | Mesh need | Entries |");
  L.push("| --- | --- | --- |");
  for (const [k, r] of commandRoutes) L.push(`| ${code(k)} | ${r.need} | ${(r.ids ?? []).map(code).join(", ")} |`);
  L.push("");
  L.push("## Chat socket frames");
  L.push("");
  L.push("The `type` of every `ChatClientMessage` (`shared/protocol.ts`), the frames a page sends on `/ws/chat`:");
  L.push("");
  L.push(inv.frames.map(code).join(", "));
  L.push("");
  L.push("## Keydown listeners on the document or the window");
  L.push("");
  L.push("`global` is a bare `addEventListener` call, which is the window's.");
  L.push("");
  L.push("| File | Listeners |");
  L.push("| --- | --- |");
  for (const f of Object.keys(inv.keydown).sort()) L.push(`| ${code(f)} | ${inv.keydown[f]!.join(", ")} |`);
  L.push("");
  L.push("## Hand-written tool specs");
  L.push("");
  L.push("Per file, the tool names its object literals declare (`<computed: …>` where the name isn't a literal).");
  L.push("");
  L.push("| File | Count | Names |");
  L.push("| --- | ---: | --- |");
  for (const f of Object.keys(inv.tools).sort()) L.push(`| ${code(f)} | ${inv.tools[f]!.length} | ${inv.tools[f]!.map((n) => code(cell(n))).join(", ")} |`);
  L.push("");
  return L.join("\n");
}
